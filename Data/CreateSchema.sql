C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME, 
STRFTIME('%M:%f',JULIANDAY(P.RANKINGTIME)- LAG(JULIANDAY(P.RANKINGTIME), 1) 
