FROM COMPETITORS C INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID;

(* Circuit: more laps beat fewer (lapped riders behind), then finish time.
   _BYCLASS = same order filtered by CLASS (renumbered places), not a separate race.
   STARTTIME = green-flag SYSTEM passing (FLAGS=2, HITS=cSystemHitsStarted=-2). *)
CREATE VIEW RANKING_CIRCUIT AS
SELECT ROW_NUMBER() OVER (
  PARTITION BY P.RACEID
  ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.FINISHTIME IS NULL, P.FINISHTIME, C.BIB
) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME,
STRFTIME('%M:%f',JULIANDAY(P.FINISHTIME)- LAG(JULIANDAY(P.FINISHTIME), 1)
OVER (PARTITION BY P.RACEID ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.FINISHTIME IS NULL, P.FINISHTIME, C.BIB)) GAP,
P.FINISHTIME, GS.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID
FROM COMPETITORS C
INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID
LEFT JOIN (
  SELECT RACEID, MIN(PASSINGTIME) AS STARTTIME
  FROM PASSINGS
  WHERE FLAGS = 2 AND HITS = -2
  GROUP BY RACEID
) GS ON GS.RACEID = P.RACEID;

CREATE VIEW RANKING_CIRCUIT_BYCLASS AS
SELECT ROW_NUMBER() OVER (
  PARTITION BY P.RACEID, C.CLASS
  ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.FINISHTIME IS NULL, P.FINISHTIME, C.BIB
) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME,
STRFTIME('%M:%f',JULIANDAY(P.FINISHTIME)- LAG(JULIANDAY(P.FINISHTIME), 1)
OVER (PARTITION BY P.RACEID, C.CLASS ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.FINISHTIME IS NULL, P.FINISHTIME, C.BIB)) GAP,
P.FINISHTIME, GS.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID
FROM COMPETITORS C
INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID
LEFT JOIN (
  SELECT RACEID, MIN(PASSINGTIME) AS STARTTIME
  FROM PASSINGS
  WHERE FLAGS = 2 AND HITS = -2
  GROUP BY RACEID
) GS ON GS.RACEID = P.RACEID;

(* Criterium (WB Straße § 11.2.3): most laps win; equal laps → points; later
   points break remaining ties (CRITRANKINGVALUE). Lap-gainers may exceed
   RACES.LAPS. Points are race-wide. _BYCLASS filters the overall order by CLASS
   (renumbered places) — no separate points. STARTTIME = green-flag SYSTEM passing. *)
CREATE VIEW RANKING_CRITERIUM AS
SELECT ROW_NUMBER() OVER (
  PARTITION BY P.RACEID
  ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.POINTS DESC,
    P.CRITRANKINGVALUE IS NULL, P.CRITRANKINGVALUE DESC, C.BIB
) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID,
P.LAPS, P.POINTS, P.CRITRANKINGVALUE, P.RANKINGTIME,
STRFTIME('%M:%f',JULIANDAY(P.FINISHTIME)- LAG(JULIANDAY(P.FINISHTIME), 1)
OVER (PARTITION BY P.RACEID ORDER BY P.DNS, P.DNF, P.DSQ, P.LAPS DESC, P.POINTS DESC,
  P.CRITRANKINGVALUE IS NULL, P.CRITRANKINGVALUE DESC, C.BIB)) GAP,
P.FINISHTIME, GS.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID
FROM COMPETITORS C
INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID
LEFT JOIN (
  SELECT RACEID, MIN(PASSINGTIME) AS STARTTIME
  FROM PASSINGS
  WHERE FLAGS = 2 AND HITS = -2
  GROUP BY RACEID
) GS ON GS.RACEID = P.RACEID;

