  WHERE VALIDTO IS NULL;

CREATE VIEW RANKING_TIMETRIAL AS
SELECT ROW_NUMBER() OVER (PARTITION BY P.RACEID ORDER BY P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME, 
STRFTIME('%M:%f',JULIANDAY(P.RANKINGTIME)- LAG(JULIANDAY(P.RANKINGTIME), 1) 
OVER (PARTITION BY P.RACEID ORDER BY P.LAPS DESC, P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME))  GAP, 
P.FINISHTIME, P.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID 
FROM COMPETITORS C INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID; 

