CREATE TABLE EVENTS
(
        EVENTID INTEGER PRIMARY KEY,
        ORGANIZER VARCHAR(80),
        TITLE VARCHAR(80),
        DATEFROM DATETIME,
        DATETO DATETIME
);

CREATE TABLE TRANSPONDERS
(
        SHORTID INTEGER PRIMARY KEY,
        CHIPID VARCHAR(10),
        LOWBATTERYSTATUS INTEGER,
        FIRSTLOWBATTERYTIME DATETIME
 );
 
 CREATE TABLE SYSSETTINGS
 (
        SETTINGID INTEGER PRIMARY KEY,
        SETTINGNAME VARCHAR(30),
        SETTINGDATA TEXT
 );
 
 CREATE TABLE DICTIONARY
 (
        TABLENAME VARCHAR(30),
        COLUMNNAME VARCHAR(30),
        DE VARCHAR(30),
        EN VARCHAR(30)
 );

 CREATE TABLE COMPETITORS
 (
        COMPETITORID INTEGER PRIMARY KEY,
        CLASS VARCHAR(30),
        BIB INTEGER,
        FIRSTNAME VARCHAR(50),
        LASTNAME VARCHAR(50),
        CLUB VARCHAR(50),
        TEAM VARCHAR(50),
        NATIONALITY VARCHAR(50),
        NATIONALITYISO VARCHAR(3),
        UCIID VARCHAR(10),
        HANDICAPFACTOR REAL,
        STARTTIME DATETIME,
        ADDITIONAL1 VARCHAR(100),
        ADDITIONAL2 VARCHAR(100),
        ADDITIONAL3 VARCHAR(100),
        TRANSPONDERID INTEGER
);

CREATE TABLE TEAMS
(
        TEAMID INTEGER PRIMARY KEY,
        TEAMNAME VARCHAR(50),
        MAXNUMBEROFMEMBERS INTEGER,
        RANKEDMEMBERNUMBER INTEGER
);

CREATE TABLE TEAMMEMBERS
(
        TEAMID INTEGER,
        COMPETITORID INTEGER
);

CREATE TABLE RACES
(
        RACEID INTEGER PRIMARY KEY,
        EVENTID INTEGER,
        TITLE VARCHAR(50),
        STARTTIME DATETIME,
        RACETYPE INTEGER,
        LAPS INTEGER,
        DISTANCE REAL,
        FIRSTPASSINGISLAP BOOLEAN,
        MINLAPDURATION INTEGER,
        STATUS INTEGER
);
        
CREATE TABLE PARTICIPATION
(
        PARTICIPATIONID INTEGER PRIMARY KEY,
        RACEID INTEGER,
        COMPETITORID INTEGER,
        STARTTIME DATETIME,
        FINISHTIME DATETIME,
        RANKINGTIME DATETIME,
        CURRENTRANKING INTEGER,
        LAPS INTEGER,
        POINTS INTEGER,
        CRITRANKINGVALUE VARCHAR(100),
        PENALTIES VARCHAR,
        DNS BOOLEAN,
        DNF BOOLEAN,
        DSQ BOOLEAN
);

CREATE TABLE PASSINGS
(
        PASSINGID INTEGER PRIMARY KEY,
        PASSINGNUMBER INTEGER,
        TRANSPONDERID INTEGER,
        PASSINGTIME TIMESTAMP,
        SIGNALSTRENGTH INTEGER,
        HITS INTEGER,
        FLAGS INTEGER,
        SPORT INTEGER,
        DECODERID VARCHAR(30)
);
        