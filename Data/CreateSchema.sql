CREATE TABLE EVENTS
(
        EVENTID INTEGER PRIMARY KEY,
        ORGANIZER VARCHAR(80),
        TITLE VARCHAR(80),
        DATEFROM TIMESTAMP,
        DATETO TIMESTAMP
);

CREATE TABLE TRANSPONDERS
(
        CHIPID VARCHAR(10) PRIMARY KEY,
        SHORTID INTEGER NOT NULL,
        LOWBATTERYSTATUS INTEGER,
        FIRSTLOWBATTERYTIME TIMESTAMP
 );
 
 CREATE INDEX IDX_TX_SHORTID ON TRANSPONDERS (SHORTID, CHIPID);

 CREATE TABLE SYSSETTINGS
 (
        SETTINGID INTEGER PRIMARY KEY,
        SETTINGNAME VARCHAR(30),
        SETTINGDATA TEXT
 );
 
 CREATE TABLE DICTIONARY
 (
        TABLENAME VARCHAR(30),
        COLUMNNAME VARCHAR(30),
        DE VARCHAR(30),
        EN VARCHAR(30)
 );
CREATE INDEX IDX_DICT ON DICTIONARY (TABLENAME, COLUMNNAME);

 CREATE TABLE COMPETITORS
 (
        COMPETITORID INTEGER PRIMARY KEY,
        CLASS VARCHAR(30) NOT NULL,
        BIB INTEGER NOT NULL,
        FIRSTNAME VARCHAR(50),
        LASTNAME VARCHAR(50),
        CLUB VARCHAR(50),
        TEAM VARCHAR(50),
        NATIONALITY VARCHAR(50),
        NATIONALITYISO VARCHAR(3),
        UCIID VARCHAR(10),
        HANDICAPFACTOR REAL NOT NULL DEFAULT 0,
        STARTTIME TIMESTAMP,
        ADDITIONAL1 VARCHAR(100),
        ADDITIONAL2 VARCHAR(100),
        ADDITIONAL3 VARCHAR(100),
        CHIPID VARCHAR(10)
);
CREATE INDEX IDX_COMP_1 ON COMPETITORS (CLASS,BIB);
CREATE INDEX IDX_COMP_2 ON COMPETITORS (CHIPID,CLASS);

CREATE TABLE TEAMS
(
        TEAMID INTEGER PRIMARY KEY,
        TEAMNAME VARCHAR(50),
        MAXNUMBEROFMEMBERS INTEGER,
        RANKEDMEMBERNUMBER INTEGER
);

CREATE TABLE TEAMMEMBERS
(
        TEAMID INTEGER NOT NULL,
        COMPETITORID INTEGER NOT NULL
);
CREATE INDEX IDX_TEAM_MEMBER  ON TEAMMEMBERS (TEAMID, COMPETITORID);

CREATE TABLE RACES
(
        RACEID INTEGER PRIMARY KEY,
        EVENTID INTEGER,
        TITLE VARCHAR(50),
        STARTTIME TIMESTAMP,
        RACETYPE INTEGER NOT NULL DEFAULT 0,
        LAPS INTEGER NOT NULL DEFAULT 1,
        DISTANCE REAL NOT NULL DEFAULT 0.0,
        FIRSTPASSINGISLAP BOOLEAN NOT NULL DEFAULT FALSE,
        MINLAPDURATION INTEGER NOT NULL DEFAULT 120,
        STATUS INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IDX_RACES_STARTTIME ON RACES (STARTTIME);

CREATE TABLE PARTICIPATION
(
        PARTICIPATIONID INTEGER PRIMARY KEY,
        RACEID INTEGER NOT NULL,
        COMPETITORID INTEGER NOT NULL,
        STARTTIME TIMESTAMP,
        FINISHTIME TIMESTAMP,
        RANKINGTIME TIMESTAMP,
        CURRENTRANKING INTEGER,
        LAPS INTEGER NOT NULL DEFAULT 0,
        POINTS INTEGER  NOT NULL DEFAULT 0,
        CRITRANKINGVALUE VARCHAR(100),
        PENALTIES VARCHAR,
        DNS BOOLEAN NOT NULL DEFAULT FALSE,
        DNF BOOLEAN NOT NULL DEFAULT FALSE,
        DSQ BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IDX_PARTICIP ON PARTICIPATION (RACEID, COMPETITORID);

CREATE TABLE PASSINGS
(
        PASSINGID INTEGER PRIMARY KEY,
        PASSINGNUMBER INTEGER,
        CHIPID INTEGER,
        PASSINGTIME TIMESTAMP,
        SIGNALSTRENGTH INTEGER,
        HITS INTEGER,
        FLAGS INTEGER,
        SPORT INTEGER,
        DECODERID VARCHAR(30),
        RACEID INTEGER DEFAULT -1,
        PASSINGSTATUS INTEGER DEFAULT 0
);

CREATE INDEX IDX_PASSINGS_1 ON PASSINGS (CHIPID, PASSINGTIME);

CREATE INDEX IDX_PASSINGS_2 ON PASSINGS (PASSINGTIME, CHIPID);

CREATE VIEW RANKING_TIMETRIAL AS
SELECT ROW_NUMBER() OVER (PARTITION BY P.RACEID ORDER BY P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME, 
STRFTIME('%M:%f',JULIANDAY(P.RANKINGTIME)- LAG(JULIANDAY(P.RANKINGTIME), 1) 
OVER (PARTITION BY P.RACEID ORDER BY P.LAPS DESC, P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME))  GAP, 
P.FINISHTIME, P.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID 
FROM COMPETITORS C INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID; 

CREATE VIEW RANKING_TIMETRIAL_BYCLASS AS
SELECT ROW_NUMBER() OVER (PARTITION BY C.CLASS, 1 ORDER BY C.CLASS, P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME) CURRENTRANKING,
C.CLASS, C.BIB, C.LASTNAME || ', ' || C.FIRSTNAME NAME, IFNULL(C.TEAM, C.CLUB) TEAM, P.RACEID, P.LAPS, P.RANKINGTIME, 
STRFTIME('%M:%f',JULIANDAY(P.RANKINGTIME)- LAG(JULIANDAY(P.RANKINGTIME), 1) 
OVER (PARTITION BY C.CLASS, 1 ORDER BY C.CLASS, P.LAPS DESC, P.RANKINGTIME IS NULL, P.RANKINGTIME, P.STARTTIME))  GAP, 
P.FINISHTIME, P.STARTTIME, P.DNS, P.DNF, P.DSQ, P.PENALTIES, P.PARTICIPATIONID, P.COMPETITORID, C.UCIID
FROM COMPETITORS C INNER JOIN PARTICIPATION P ON C.COMPETITORID = P.COMPETITORID;
